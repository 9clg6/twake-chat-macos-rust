#[test]
fn text_that_is_not_json_is_an_error_that_says_so() {
    assert!(message("{ not json").contains("invalid JSON"));
    assert!(message("").contains("invalid JSON"));
}

#[test]
fn json_that_is_not_an_object_is_an_error() {
    assert!(generate("[1, 2]").is_err());
    assert!(generate("null").is_err());
}

#[test]
fn a_missing_icons_section_names_the_key() {
    let text = message(&format!("{{\"source\":\"{SOURCE}\"}}"));
    assert!(text.contains("icons"), "{text}");
}

#[test]
fn a_missing_source_names_the_key() {
    let text = message("{\"icons\":{}}");
    assert!(text.contains("source"), "{text}");
}

#[test]
fn an_icon_without_a_viewbox_names_the_icon_and_the_key() {
    let text = message(&json(&["\"a-b\":{\"body\":\"<g/>\"}".to_string()]));
    assert!(text.contains("a-b") && text.contains("viewBox"), "{text}");
}

#[test]
fn an_icon_without_a_body_names_the_icon_and_the_key() {
    let text = message(&json(&["\"a-b\":{\"viewBox\":\"0 0 1 1\"}".to_string()]));
    assert!(text.contains("a-b") && text.contains("body"), "{text}");
}

#[test]
fn a_body_that_is_not_text_is_refused() {
    let text = message(&json(&[
        "\"a-b\":{\"viewBox\":\"0 0 1 1\",\"body\":3}".to_string()
    ]));
    assert!(text.contains("a-b") && text.contains("body"), "{text}");
}

#[test]
fn an_icon_that_is_not_an_object_is_refused() {
    assert!(message(&json(&["\"a-b\":\"<g/>\"".to_string()])).contains("a-b"));
}

#[test]
fn a_bad_viewbox_is_refused_with_the_icon_and_the_text() {
    for bad in [
        "0 0 16",
        "0 0 16 16 1",
        "a b c d",
        "",
        "0 0 0 16",
        "0 0 16 0",
        "0 0 16 -1",
    ] {
        let text = message(&one("a-b", bad, "<g/>"));
        assert!(
            text.contains("a-b") && text.contains("viewBox"),
            "{bad:?}: {text}"
        );
        if !bad.is_empty() {
            assert!(text.contains(bad), "{bad:?}: {text}");
        }
    }
}

#[test]
fn an_id_that_is_not_kebab_case_is_refused_and_quoted() {
    for bad in ["Album", "a_b", "a--b", "-a", "a-", "a b", ""] {
        let text = message(&one(bad, "0 0 1 1", "<g/>"));
        assert!(!text.is_empty(), "{bad:?} accepted");
        assert!(text.contains(bad), "{bad:?}: {text}");
    }
}
