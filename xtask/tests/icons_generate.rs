//! `xtask::icons::generate`: `docs/spec/icons.json` (text) in, `generated.rs` (text) out.
//! Need: the icon set is data, the crate is generated, deterministic, checked in CI.
//! The tests use small fixtures and compare whitespace-squashed text, so rustfmt-style layout is
//! the implementer's choice. Public items used: `docs/dev/icons-api-sketch.md`.

use xtask::icons::generate;

const SOURCE: &str = "@linagora/twake-icons@3.0.0";

fn entry(id: &str, view_box: &str, body: &str) -> String {
    format!("\"{id}\":{{\"viewBox\":\"{view_box}\",\"body\":\"{body}\"}}")
}

fn json(entries: &[String]) -> String {
    format!(
        "{{\"source\":\"{SOURCE}\",\"icons\":{{{}}}}}",
        entries.join(",")
    )
}

fn one(id: &str, view_box: &str, body: &str) -> String {
    json(&[entry(id, view_box, body)])
}

fn squash(text: &str) -> String {
    text.chars().filter(|c| !c.is_whitespace()).collect()
}

fn out(json: &str) -> String {
    generate(json).map(|text| squash(&text)).unwrap_or_default()
}

fn message(json: &str) -> String {
    generate(json)
        .err()
        .map(|e| e.to_string())
        .unwrap_or_default()
}

/// Squashed `needles` all appear in `haystack`, in this order.
fn assert_in_order(haystack: &str, needles: &[&str]) {
    let mut from = 0;
    for needle in needles {
        let at = haystack[from..].find(*needle);
        assert!(
            at.is_some(),
            "{needle:?} missing or out of order after byte {from}"
        );
        from += at.unwrap_or(0) + needle.len();
    }
}

// ------------------------------------------------------------------ header and icons

#[test]
fn the_file_says_it_is_generated_and_from_which_package() {
    let text = generate(&one("a", "0 0 16 16", "<g/>")).unwrap_or_default();
    let first = text.lines().next().unwrap_or_default();
    assert!(
        first.starts_with("// @generated by `cargo xtask icons`"),
        "{first}"
    );
    assert!(first.contains(SOURCE), "{first}");
    assert!(text.ends_with('\n'));
}

#[test]
fn an_icon_becomes_a_constant_with_its_id_viewbox_and_body() {
    let text = out(&one("album-add", "0 0 16 16", "<g/>"));
    let want = "pubconstALBUM_ADD:Icon=Icon{id:\"album-add\",view_box:ViewBox{min_x:0.0,min_y:0.0,width:16.0,height:16.0},body:\"<g/>\"};";
    assert!(text.contains(want), "{text}");
}

#[test]
fn the_four_viewbox_numbers_keep_their_place_and_their_fractions() {
    let text = out(&one("a", "-1 -2.5 24 20.5", "<g/>"));
    assert!(
        text.contains("min_x:-1.0,min_y:-2.5,width:24.0,height:20.5"),
        "{text}"
    );
}

#[test]
fn a_viewbox_may_be_separated_by_commas() {
    let text = out(&one("a", "0,0, 32,24", "<g/>"));
    assert!(
        text.contains("min_x:0.0,min_y:0.0,width:32.0,height:24.0"),
        "{text}"
    );
}

#[test]
fn quotes_and_backslashes_of_the_body_are_escaped_in_the_literal() {
    let text = out(&one("a", "0 0 1 1", "<path d=\\\"M0\\\\1\\\"/>"));
    assert!(text.contains("body:\"<pathd=\\\"M0\\\\1\\\"/>\""), "{text}");
}

#[test]
fn a_newline_of_the_body_is_escaped_in_the_literal() {
    let text = out(&one("a", "0 0 1 1", "<g>\\n</g>"));
    assert!(text.contains("body:\"<g>\\n</g>\""), "{text}");
}

#[test]
fn an_empty_set_is_valid() {
    let text = out(&json(&[]));
    assert!(text.contains("pubstaticALL:&[Icon]=&[];"), "{text}");
}

// ------------------------------------------------------------------ names

#[test]
fn the_name_is_the_id_in_screaming_snake_case() {
    let text = out(&json(&[
        entry("x", "0 0 1 1", "<g/>"),
        entry("chevron-down-small", "0 0 1 1", "<g/>"),
    ]));
    assert!(text.contains("pubconstX:Icon"), "{text}");
    assert!(text.contains("pubconstCHEVRON_DOWN_SMALL:Icon"), "{text}");
}

#[test]
fn a_name_that_starts_with_a_digit_gets_the_prefix() {
    let text = out(&one("3d-rotate", "0 0 1 1", "<g/>"));
    assert!(
        text.contains("pubconstI_3D_ROTATE:Icon=Icon{id:\"3d-rotate\""),
        "{text}"
    );
    assert!(!text.contains("pubconst3D"));
}

#[test]
fn an_icon_called_all_does_not_take_the_name_of_the_static() {
    let text = out(&one("all", "0 0 1 1", "<g/>"));
    assert!(
        text.contains("pubconstI_ALL:Icon=Icon{id:\"all\""),
        "{text}"
    );
    assert!(!text.contains("pubconstALL:"));
    assert_eq!(text.matches("pubstaticALL:").count(), 1);
}

#[test]
fn two_ids_with_the_same_name_are_refused_and_both_named() {
    let both = json(&[
        entry("all", "0 0 1 1", "<g/>"),
        entry("i-all", "0 0 1 1", "<g/>"),
    ]);
    let text = message(&both);
    assert!(text.contains("all") && text.contains("i-all"), "{text}");
    assert!(text.contains("I_ALL"), "{text}");
}

// ------------------------------------------------------------------ order

fn three() -> Vec<String> {
    ["zz", "a1", "a-b"]
        .iter()
        .map(|id| entry(id, "0 0 1 1", "<g/>"))
        .collect()
}

#[test]
fn constants_and_the_list_are_sorted_by_id_not_by_name() {
    let text = out(&json(&three()));
    assert_in_order(
        &text,
        &[
            "pubconstA_B:Icon",
            "pubconstA1:Icon",
            "pubconstZZ:Icon",
            "pubstaticALL:&[Icon]=&[",
            "A_B",
            "A1",
            "ZZ",
        ],
    );
}

#[test]
fn the_list_holds_each_icon_once() {
    let text = out(&json(&three()));
    let list = text.split("pubstaticALL:").nth(1).unwrap_or_default();
    for name in ["A_B", "A1", "ZZ"] {
        assert_eq!(list.matches(name).count(), 1, "{name} in {list}");
    }
}

#[test]
fn the_same_bytes_come_out_whatever_the_key_order() {
    let mut reversed = three();
    reversed.reverse();
    let (forward, backward) = (generate(&json(&three())), generate(&json(&reversed)));
    assert!(forward.is_ok());
    assert_eq!(forward, backward);
}

