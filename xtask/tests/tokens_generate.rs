//! `xtask::tokens::generate`: `docs/spec/tokens.json` (text) in, `generated.rs` (text) out.
//! Need: the design system is data (`design-system.md` section 4, ARCHITECTURE.md section 3:
//! `twake-tokens` is generated, deterministic, checked in CI). The tests use a small fixture
//! and compare whitespace-squashed text, so rustfmt-style layout is the implementer's choice.
//! Public items used are listed in `docs/dev/tokens-api-sketch.md`.

use xtask::tokens::generate;

const SHADES: [&str; 10] = [
    "#f6fbff", "#e3f1ff", "#d2e9ff", "#bfdfff", "#7bbdff", "#46a2ff", "#0a84ff", "#006bd8",
    "#0157ad", "#082139",
];
const KEYS: [&str; 10] = [
    "50", "100", "200", "300", "400", "500", "600", "700", "800", "900",
];

fn palette(contrast: Option<&str>, reversed: bool) -> String {
    let mut pairs: Vec<String> = KEYS
        .iter()
        .zip(SHADES)
        .map(|(key, hex)| format!("\"{key}\":\"{hex}\""))
        .collect();
    if let Some(color) = contrast {
        pairs.push(format!("\"ContrastText\":\"{color}\""));
    }
    if reversed {
        pairs.reverse();
    }
    format!("{{{}}}", pairs.join(","))
}

fn raw(reversed: bool) -> String {
    format!(
        "{{\"Primary\":{},\"Info\":{}}}",
        palette(Some("#fff"), reversed),
        palette(None, reversed)
    )
}

fn json(body: &str) -> String {
    format!("{{\"twakeMuiVersion\":\"9.9.9\",{body}}}")
}

fn base() -> String {
    json(&format!("\"paletteRaw\":{}", raw(false)))
}

fn squash(text: &str) -> String {
    text.chars().filter(|c| !c.is_whitespace()).collect()
}

fn out(json: &str) -> Result<String, xtask::tokens::Error> {
    generate(json).map(|text| squash(&text))
}

/// Squashed `needles` all appear in `haystack`, in this order.
fn assert_in_order(haystack: &str, needles: &[&str]) {
    let mut from = 0;
    for needle in needles {
        let wanted = squash(needle);
        let at = haystack[from..].find(&wanted);
        assert!(
            at.is_some(),
            "{wanted:?} missing or out of order after byte {from}"
        );
        from += at.unwrap_or(0) + wanted.len();
    }
}

fn scheme(paper: &str, text_secondary: &str, divider: &str) -> String {
    let tone = "\"light\":\"#d2e9ff\",\"main\":\"#0a84ff\",\"dark\":\"#006bd8\",\"contrastText\":\"#fff\",\"mainChannel\":\"10 132 255\"";
    format!(
        "{{\"palette\":{{\"mode\":\"x\",\"primary\":{{{tone}}},\"secondary\":{{{tone}}},\"error\":{{{tone}}},\"warning\":{{{tone}}},\"success\":{{{tone}}},\"info\":{{{tone}}},\
         \"text\":{{\"primary\":\"#fff\",\"secondary\":\"{text_secondary}\",\"disabled\":\"rgba(0, 0, 0, 1)\",\"icon\":\"#fff\"}},\
         \"background\":{{\"default\":\"#F3F6F9\",\"paper\":\"{paper}\",\"contrast\":\"rgba(66, 66, 68, 0.048)\"}},\
         \"border\":{{\"main\":\"#111111\",\"disabled\":\"#222222\",\"ghost\":\"#333333\",\"ghostDisabled\":\"#444444\"}},\
         \"divider\":\"{divider}\"}},\"shadows\":[\"none\"]}}"
    )
}

fn with_schemes() -> String {
    let light = scheme("#fff", "rgba(66, 66, 68, 0.64)", "rgba(66, 66, 68, 0.12)");
    let dark = scheme(
        "#4E5052",
        "rgba(255, 255, 255, 0.64)",
        "rgba(255, 255, 255, 0.16)",
    );
    json(&format!(
        "\"paletteRaw\":{},\"schemes\":{{\"dark\":{dark},\"light\":{light}}}",
        raw(false)
    ))
}

// ------------------------------------------------------------------ header and palettes

#[test]
fn the_file_says_it_is_generated_and_from_which_twake_mui() {
    let text = generate(&base()).unwrap_or_default();
    let first = text.lines().next().unwrap_or_default();
    assert!(
        first.starts_with("// @generated by `cargo xtask tokens`"),
        "{first}"
    );
    assert!(first.contains("twake-mui 9.9.9"), "{first}");
}

#[test]
fn each_shade_becomes_a_colour_in_order_from_50_to_900() {
    let text = out(&base()).unwrap_or_default();
    let steps = [
        "pub const PRIMARY: Palette",
        "Rgba8::new(246, 251, 255, 255)",
        "Rgba8::new(227, 241, 255, 255)",
        "Rgba8::new(210, 233, 255, 255)",
        "Rgba8::new(191, 223, 255, 255)",
        "Rgba8::new(123, 189, 255, 255)",
        "Rgba8::new(70, 162, 255, 255)",
        "Rgba8::new(10, 132, 255, 255)",
        "Rgba8::new(0, 107, 216, 255)",
        "Rgba8::new(1, 87, 173, 255)",
        "Rgba8::new(8, 33, 57, 255)",
    ];
    assert_in_order(&text, &steps);
}

#[test]
fn a_contrast_text_becomes_some_and_its_absence_none() {
    let text = out(&base()).unwrap_or_default();
    assert!(text.contains("contrast_text:Some(Rgba8::new(255,255,255,255))"));
    assert!(text.contains("contrast_text:None"));
}

#[test]
fn palettes_are_named_in_upper_case_after_the_json_key() {
    let text = out(&base()).unwrap_or_default();
    assert!(text.contains("pubconstPRIMARY:Palette"));
    assert!(text.contains("pubconstINFO:Palette"));
    assert!(
        !text.contains("pubconstERROR:Palette"),
        "absent palette must not be invented"
    );
}

#[test]
fn shade_order_in_the_json_does_not_change_the_output() {
    let forward = generate(&base());
    let backward = generate(&json(&format!("\"paletteRaw\":{}", raw(true))));
    assert!(forward.is_ok());
    assert_eq!(forward, backward);
}

#[test]
fn the_same_input_gives_the_same_bytes() {
    assert_eq!(generate(&with_schemes()), generate(&with_schemes()));
}

#[test]
fn the_file_ends_with_a_newline() {
    assert!(generate(&base()).unwrap_or_default().ends_with('\n'));
}

#[test]
fn shorthand_hex_in_the_json_is_expanded() {
    let body = format!(
        "\"paletteRaw\":{{\"Primary\":{}}}",
        palette(Some("#abc"), false)
    );
    let text = out(&json(&body)).unwrap_or_default();
    assert!(text.contains("contrast_text:Some(Rgba8::new(170,187,204,255))"));
}

// ------------------------------------------------------------------ schemes

#[test]
fn light_comes_before_dark_whatever_the_json_order() {
    let text = out(&with_schemes()).unwrap_or_default();
    assert_in_order(
        &text,
        &["pub const LIGHT: Scheme", "pub const DARK: Scheme"],
    );
}

#[test]
fn schemes_differ_where_the_json_differs() {
    let text = out(&with_schemes()).unwrap_or_default();
    let dark_at = text.find("pubconstDARK:Scheme").unwrap_or(0);
    let (light, dark) = text.split_at(dark_at);
    assert!(light.contains("Rgba8::new(255,255,255,255)"));
    assert!(
        dark.contains("Rgba8::new(78,80,82,255)"),
        "paper #4E5052 in the dark scheme"
    );
    assert!(!light.contains("Rgba8::new(78,80,82,255)"));
}

#[test]
fn rgba_colours_become_bytes_with_the_alpha_rounded() {
    let text = out(&with_schemes()).unwrap_or_default();
    assert!(text.contains("Rgba8::new(66,66,68,163)"), "0.64 -> 163");
    assert!(text.contains("Rgba8::new(66,66,68,31)"), "0.12 -> 31");
    assert!(text.contains("Rgba8::new(255,255,255,41)"), "0.16 -> 41");
    assert!(text.contains("Rgba8::new(0,0,0,255)"), "alpha 1 -> 255");
}

#[test]
fn a_json_without_schemes_still_generates_the_palettes() {
    let text = out(&base()).unwrap_or_default();
    assert!(!text.contains("pubconstLIGHT"));
    assert!(text.contains("pubconstPRIMARY:Palette"));
}

// ------------------------------------------------------------------ spacing, radius, type

#[test]
fn spacing_radius_and_breakpoints_become_f32_constants() {
    let body = format!(
        "\"paletteRaw\":{},\"spacing\":{{\"unit\":\"var(--twake-spacing, 8px)\"}},\
         \"shape\":{{\"borderRadius\":6}},\
         \"radius\":{{\"none\":\"0\",\"sm\":\"4px\",\"pill\":\"100px\"}},\
         \"breakpoints\":{{\"xs\":0,\"md\":769}}",
        raw(false)
    );
    let text = out(&json(&body)).unwrap_or_default();
    for line in [
        "pub const SPACING: f32 = 8.0;",
        "pub const SHAPE_RADIUS: f32 = 6.0;",
        "pub const RADIUS_NONE: f32 = 0.0;",
        "pub const RADIUS_SM: f32 = 4.0;",
        "pub const RADIUS_PILL: f32 = 100.0;",
        "pub const BREAKPOINT_XS: f32 = 0.0;",
        "pub const BREAKPOINT_MD: f32 = 769.0;",
    ] {
        assert!(text.contains(&squash(line)), "missing {line}");
    }
}

#[test]
fn a_type_style_with_a_ratio_line_height_and_letter_spacing() {
    let typography = "\"typography\":{\"h5\":{\"fontSize\":16,\"fontWeight\":600,\"lineHeight\":1.313,\"letterSpacing\":\"0.15px\",\"fontFamily\":\"x\"}}";
    let text = out(&json(&format!(
        "\"paletteRaw\":{},{typography}",
        raw(false)
    )))
    .unwrap_or_default();
    let parts = [
        "pub const TYPE_H5: TypeSpec",
        "font_size: 16.0",
        "font_weight: 600",
        "line_height: LineHeight::Ratio(1.313)",
        "letter_spacing: 0.15",
    ];
    assert_in_order(&text, &parts);
}

#[test]
fn a_pixel_line_height_and_a_missing_letter_spacing() {
    let typography = "\"typography\":{\"overline\":{\"fontSize\":11,\"fontWeight\":500,\"lineHeight\":\"13px\"},\"h1\":{\"fontSize\":45,\"fontWeight\":600,\"lineHeight\":1.087}}";
    let text = out(&json(&format!(
        "\"paletteRaw\":{},{typography}",
        raw(false)
    )))
    .unwrap_or_default();
    assert!(text.contains("line_height:LineHeight::Px(13.0)"));
    assert!(text.contains("pubconstTYPE_H1:TypeSpec"));
    assert!(text.contains("letter_spacing:0.0"));
}

#[test]
fn the_inherit_pseudo_style_is_not_a_constant() {
    let typography = "\"typography\":{\"inherit\":{\"fontSize\":\"inherit\",\"fontWeight\":\"inherit\",\"lineHeight\":\"inherit\"},\"h1\":{\"fontSize\":45,\"fontWeight\":600,\"lineHeight\":1.087}}";
    let result = out(&json(&format!(
        "\"paletteRaw\":{},{typography}",
        raw(false)
    )));
    let text = result.unwrap_or_default();
    assert!(text.contains("pubconstTYPE_H1"));
    assert!(!text.contains("TYPE_INHERIT"));
}

// ------------------------------------------------------------------ errors

fn message(json: &str) -> String {
    generate(json)
        .err()
        .map(|e| e.to_string())
        .unwrap_or_default()
}

#[test]
fn text_that_is_not_json_is_an_error_that_says_so() {
    assert!(message("{ not json").contains("invalid JSON"));
    assert!(message("").contains("invalid JSON"));
}

#[test]
fn json_that_is_not_an_object_is_an_error() {
    assert!(generate("[1, 2]").is_err());
    assert!(generate("null").is_err());
}

#[test]
fn a_missing_palette_section_names_the_key() {
    assert!(message(&json("\"typography\":{}")).contains("paletteRaw"));
}

#[test]
fn a_bad_colour_is_refused_and_quoted() {
    let bad = "{\"twakeMuiVersion\":\"1\",\"paletteRaw\":{\"Primary\":{\"50\":\"#12g\"}}}";
    assert!(message(bad).contains("#12g"));
}

#[test]
fn a_palette_missing_a_shade_names_palette_and_shade() {
    let mut pairs: Vec<String> = KEYS
        .iter()
        .zip(SHADES)
        .filter(|(key, _)| **key != "600")
        .map(|(key, hex)| format!("\"{key}\":\"{hex}\""))
        .collect();
    pairs.push("\"ContrastText\":\"#fff\"".to_string());
    let body = format!("\"paletteRaw\":{{\"Primary\":{{{}}}}}", pairs.join(","));
    let text = message(&json(&body));
    assert!(text.contains("Primary") && text.contains("600"), "{text}");
}

#[test]
fn a_scheme_missing_a_group_names_it() {
    let broken = scheme("#fff", "#000", "#000").replace("\"divider\"", "\"dividerx\"");
    let body = format!(
        "\"paletteRaw\":{},\"schemes\":{{\"light\":{broken}}}",
        raw(false)
    );
    assert!(message(&json(&body)).contains("divider"));
}

#[test]
fn a_missing_twake_mui_version_is_an_error() {
    let body = format!("{{\"paletteRaw\":{}}}", raw(false));
    assert!(message(&body).contains("twakeMuiVersion"));
}
