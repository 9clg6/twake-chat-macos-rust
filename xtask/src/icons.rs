//! `cargo xtask icons`: turns `docs/spec/icons.json` into `crates/twake-icons/src/generated.rs`.

use std::collections::BTreeMap;

use serde_json::{Map, Value};

use crate::common::{Res, fail, object, root, string};

pub use crate::common::Error;

fn is_kebab(id: &str) -> bool {
    id.split('-').all(|part| {
        !part.is_empty()
            && part
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
    })
}

/// The constant of an icon: the id in screaming snake case, `I_` before a digit or `ALL`.
fn const_name(id: &str) -> String {
    let name = id.to_uppercase().replace('-', "_");
    if name == "ALL" || name.starts_with(|c: char| c.is_ascii_digit()) {
        format!("I_{name}")
    } else {
        name
    }
}

/// `min-x min-y width height`, separated by spaces and/or commas; a drawable size.
fn view_box(id: &str, text: &str) -> Res<String> {
    let numbers = text
        .split(|c: char| c.is_whitespace() || c == ',')
        .filter(|part| !part.is_empty())
        .map(|part| part.parse::<f32>().ok().filter(|n| n.is_finite()))
        .collect::<Option<Vec<_>>>();
    match numbers.as_deref() {
        Some(&[min_x, min_y, width, height]) if width > 0.0 && height > 0.0 => Ok(format!(
            "ViewBox {{\n        min_x: {min_x:?},\n        min_y: {min_y:?},\n        width: {width:?},\n        height: {height:?}\n    }}"
        )),
        _ => fail(format!("icon {id}: bad viewBox {text:?}")),
    }
}

fn literal(body: &str) -> String {
    let escaped = body
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r");
    format!("\"{escaped}\"")
}

fn field<'a>(icon: &'a Map<String, Value>, id: &str, key: &str) -> Res<&'a str> {
    match icon.get(key) {
        Some(value) => string(value, &format!("icon {id}: {key}")),
        None => fail(format!("icon {id}: no {key}")),
    }
}

fn constant(id: &str, name: &str, raw: &Value) -> Res<String> {
    let icon = object(raw, &format!("icon {id}"))?;
    let view_box = view_box(id, field(icon, id, "viewBox")?)?;
    let body = literal(field(icon, id, "body")?);
    Ok(format!(
        "/// The `{id}` icon.\npub const {name}: Icon = Icon {{\n    id: \"{id}\",\n    view_box: {view_box},\n    body: {body}\n}};\n\n"
    ))
}

fn sections(root: &Map<String, Value>) -> Res<(&str, &Map<String, Value>)> {
    let (Some(source), Some(icons)) = (root.get("source"), root.get("icons")) else {
        let key = if root.contains_key("source") {
            "icons"
        } else {
            "source"
        };
        return fail(format!("icons.json has no {key}"));
    };
    Ok((string(source, "source")?, object(icons, "icons")?))
}

/// The constants, then `ALL`, for the icons sorted by id.
fn constants(icons: &Map<String, Value>) -> Res<String> {
    let mut taken: BTreeMap<String, &str> = BTreeMap::new();
    let mut names = Vec::new();
    let mut text = String::new();
    // `preserve_order` is on in this workspace: sort, so that the key order does not matter.
    let mut sorted: Vec<_> = icons.iter().collect();
    sorted.sort_by_key(|(id, _)| id.as_str());
    for (id, icon) in sorted {
        if !is_kebab(id) {
            return fail(format!("icon id {id:?} is not kebab-case"));
        }
        let name = const_name(id);
        if let Some(other) = taken.insert(name.clone(), id) {
            return fail(format!("icons {other} and {id} are both {name}"));
        }
        text.push_str(&constant(id, &name, icon)?);
        names.push(name);
    }
    text.push_str("/// Every icon, sorted by id.\npub static ALL: &[Icon] = &[\n");
    for name in names {
        text.push_str(&format!("    {name},\n"));
    }
    text.push_str("];\n");
    Ok(text)
}

/// The text of `generated.rs` for the text of `icons.json`.
pub fn generate(json: &str) -> Result<String, Error> {
    let root = root(json, "icons.json")?;
    let (source, icons) = sections(&root)?;
    Ok(format!(
        "// @generated by `cargo xtask icons` from docs/spec/icons.json ({source}). Do not edit.\n\nuse super::{{Icon, ViewBox}};\n\n{}",
        constants(icons)?
    ))
}
